const STOP = [2, 3, 3, 1, 1, 1, 2];
const START_B = 104;
const START_C = 105;
const CODE_B = 100;

export function encodeCode128(data: string): number[] | null {
  if (!data || !/^[\x20-\x7E]+$/.test(data)) return null;

  const values: number[] = [];
  if (data.length >= 2 && /^\d+$/.test(data)) {
    values.push(START_C);
    const pairs = Math.floor(data.length / 2);
    for (let i = 0; i < pairs; i++) {
      values.push(Number.parseInt(data.slice(2 * i, 2 * i + 2), 10));
    }
    if (data.length % 2 === 1) {
      values.push(CODE_B);
      values.push(data.charCodeAt(data.length - 1) - 32);
    }
  } else {
    values.push(START_B);
    for (let i = 0; i < data.length; i++) {
      values.push(data.charCodeAt(i) - 32);
    }
  }

  let sum = values[0] ?? 0;
  for (let i = 1; i < values.length; i++) {
    sum += (values[i] ?? 0) * i;
  }
  values.push(sum % 103);

  const widths: number[] = [];
  for (const v of values) {
    const pattern = CODE128[v];
    if (!pattern) return null;
    widths.push(...pattern);
  }
  widths.push(...STOP);
  return widths;
}
