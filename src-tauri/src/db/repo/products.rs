struct Clean {
    name: String,
    name_si: Option<String>,
    category_id: Option<String>,
    attributes: String,
}

/// Receipts and labels print in a Latin code page, so the printable name must be Latin-1.
fn printable(c: char) -> bool {
    matches!(c, ' '..='~' | '\u{00A0}'..='\u{00FF}')
}

async fn clean(conn: &mut SqliteConnection, store_id: &str, input: &ProductInput) -> AppResult<Clean> {
    let name = input.name.trim().to_owned();
    if name.is_empty() {
        return Err(AppError::validation("PRODUCT_NAME_REQUIRED", "name is empty"));
    }
    if name.chars().count() > NAME_MAX {
        return Err(AppError::validation("PRODUCT_NAME_TOO_LONG", format!("max {NAME_MAX}")));
    }
    if !name.chars().all(printable) {
        return Err(AppError::validation("PRODUCT_NAME_NOT_PRINTABLE", name));
    }
    let name_si = input.name_si.as_deref().map(str::trim).filter(|s| !s.is_empty()).map(str::to_owned);
    if name_si.as_ref().is_some_and(|s| s.chars().count() > NAME_MAX) {
        return Err(AppError::validation("PRODUCT_NAME_SI_TOO_LONG", format!("max {NAME_MAX}")));
    }
    if !(0..=MONEY_MAX).contains(&input.price) {
        return Err(AppError::validation("PRICE_INVALID", input.price.to_string()));
    }
    if let Some(min) = input.min_price
        && !(0..=input.price).contains(&min)
    {
        return Err(AppError::validation("MIN_PRICE_INVALID", format!("{min} > {}", input.price)));
    }
    if let Some(cost) = input.default_cost
        && !(0..=MONEY_MAX).contains(&cost)
    {
        return Err(AppError::validation("COST_INVALID", cost.to_string()));
    }
    let category_id = input.category_id.as_deref().map(str::trim).filter(|s| !s.is_empty()).map(str::to_owned);
    if let Some(cat) = category_id.as_deref() {
        let live: Option<String> =
            sqlx::query_scalar("SELECT id FROM categories WHERE id = ?1 AND store_id = ?2 AND deleted_at IS NULL")
                .bind(cat)
                .bind(store_id)
                .fetch_optional(&mut *conn)
                .await?;
        if live.is_none() {
            return Err(AppError::validation("CATEGORY_INVALID", cat));
        }
    }
    if input.attributes.len() > ATTR_MAX
        || input.attributes.iter().any(|(k, v)| {
            let k = k.trim();
            k.is_empty() || k.chars().count() > 20 || v.trim().is_empty() || v.chars().count() > 40
        })
    {
        return Err(AppError::validation("ATTRIBUTES_INVALID", "up to 10 name/value pairs"));
    }
    let attrs: BTreeMap<&str, &str> = input.attributes.iter().map(|(k, v)| (k.trim(), v.trim())).collect();
    let attributes = serde_json::to_string(&attrs).map_err(|e| AppError::internal(e.to_string()))?;
    Ok(Clean { name, name_si, category_id, attributes })
}

fn clean_sku(value: &str) -> AppResult<String> {
    let v = value.trim().to_uppercase();
    if v.is_empty() || v.len() > SKU_MAX || !v.chars().all(|c| c.is_ascii_alphanumeric() || c == '-') {
        return Err(AppError::validation("SKU_INVALID", v));
    }
    Ok(v)
}

fn clean_barcode(value: &str) -> AppResult<String> {
    let v = value.trim().to_owned();
    if v.len() < 4 || v.len() > CODE_MAX || !v.chars().all(|c| c.is_ascii_graphic()) {
        return Err(AppError::validation("BARCODE_INVALID", v));
    }
    if v.len() == 13 && v.chars().all(|c| c.is_ascii_digit()) && !receipt_no::is_valid_ean13(&v) {
        return Err(AppError::validation("BARCODE_CHECK_DIGIT", v));
    }
    Ok(v)
}

async fn sku_taken(conn: &mut SqliteConnection, store_id: &str, sku: &str, self_id: &str) -> AppResult<bool> {
    let hit: Option<String> = sqlx::query_scalar(
        "SELECT id FROM products WHERE store_id = ?1 AND sku = ?2 AND deleted_at IS NULL AND id <> ?3",
    )
    .bind(store_id)
    .bind(sku)
    .bind(self_id)
    .fetch_optional(&mut *conn)
    .await?;
    Ok(hit.is_some())
}

/// Used only by the in-store code generator, which never hands out a barcode already in use.
async fn barcode_taken(conn: &mut SqliteConnection, store_id: &str, code: &str, self_id: &str) -> AppResult<bool> {
    let hit: Option<String> = sqlx::query_scalar(
        "SELECT id FROM products
         WHERE store_id = ?1 AND barcode = ?2 AND deleted_at IS NULL AND is_active = 1 AND id <> ?3",
    )
    .bind(store_id)
    .bind(code)
    .bind(self_id)
    .fetch_optional(&mut *conn)
    .await?;
    Ok(hit.is_some())
}

fn code_err(e: CodeError) -> AppError {
    match e {
        CodeError::BadDeviceCode => AppError::validation("DEVICE_CODE_INVALID", e.to_string()),
        CodeError::SequenceExhausted => AppError::validation("CODE_SEQUENCE_EXHAUSTED", e.to_string()),
        CodeError::BadCheckDigit => AppError::validation("BARCODE_CHECK_DIGIT", e.to_string()),
    }
}

/// Next value of this counter's in-store code sequence (shared by SKU and barcode, so a product given both
/// gets matching numbers). Never reuses a number already on a product, even if `sku_counters` was lost
/// (reinstall, restore): the start point is the larger of the counter and the highest code in use, counting
/// 8-digit in-store barcodes and the 13-digit ones generated before them.
async fn next_code_seq(conn: &mut SqliteConnection, store_id: &str, digit: u8) -> AppResult<u32> {
    let counter: Option<i64> = sqlx::query_scalar("SELECT last_seq FROM sku_counters WHERE device_digit = ?1")
        .bind(i64::from(digit))
        .fetch_optional(&mut *conn)
        .await?;
    let in_use: Option<i64> = sqlx::query_scalar(
        "SELECT MAX(seq) FROM (
           SELECT CAST(substr(sku, 2) AS INTEGER) AS seq FROM products
            WHERE store_id = ?1 AND length(sku) = 6 AND sku GLOB ?2
           UNION ALL
           SELECT CAST(substr(barcode, 3, 5) AS INTEGER) FROM products
            WHERE store_id = ?1 AND length(barcode) = 8 AND barcode GLOB ?3
           UNION ALL
           SELECT CAST(substr(barcode, 3, 10) AS INTEGER) FROM products
            WHERE store_id = ?1 AND length(barcode) = 13 AND barcode GLOB ?4
         )",
    )
    .bind(store_id)
    .bind(format!("{digit}[0-9][0-9][0-9][0-9][0-9]"))
    .bind(format!("2{digit}[0-9][0-9][0-9][0-9][0-9][0-9]"))
    .bind(format!("2{digit}[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]"))
    .fetch_one(&mut *conn)
    .await?;
    let next = counter.unwrap_or(0).max(in_use.unwrap_or(0)) + 1;
    let next = u32::try_from(next).map_err(|_| code_err(CodeError::SequenceExhausted))?;
    set_code_counter(conn, digit, next).await?;
    Ok(next)
}

/// Remember the last sequence number this counter handed out.
async fn set_code_counter(conn: &mut SqliteConnection, digit: u8, seq: u32) -> AppResult<()> {
    sqlx::query(
        "INSERT INTO sku_counters (device_digit, last_seq) VALUES (?1, ?2)
         ON CONFLICT(device_digit) DO UPDATE SET last_seq = excluded.last_seq",
    )
    .bind(i64::from(digit))
    .bind(i64::from(seq))
    .execute(&mut *conn)
    .await?;
    Ok(())
}

/// Resolve both code choices. Generated codes skip any number a hand-typed code already took.
async fn resolve_codes(
    conn: &mut SqliteConnection,
    ctx: &WriteCtx,
    self_id: &str,
    input: &ProductInput,
) -> AppResult<(Option<String>, Option<String>)> {
    let mut sku = match &input.sku {
        CodeChoice::None | CodeChoice::Generate => None,
        CodeChoice::Manual { value } => Some(clean_sku(value)?),
    };
    let mut barcode = match &input.barcode {
        CodeChoice::None | CodeChoice::Generate => None,
        CodeChoice::Manual { value } => Some(clean_barcode(value)?),
    };
    if let Some(s) = sku.as_deref()
        && sku_taken(conn, &ctx.store_id, s, self_id).await?
    {
        return Err(AppError::validation("SKU_TAKEN", s));
    }
    let want_sku = input.sku == CodeChoice::Generate;
    let want_barcode = input.barcode == CodeChoice::Generate;
    if want_sku || want_barcode {
        let digit = receipt_no::device_digit(&ctx.device_code).map_err(code_err)?;
        loop {
            let seq = next_code_seq(conn, &ctx.store_id, digit).await?;
            let gen_sku = receipt_no::sku_code(digit, seq).map_err(code_err)?;
            let gen_barcode = receipt_no::in_store_barcode(digit, seq).map_err(code_err)?;
            let sku_clash = want_sku && sku_taken(conn, &ctx.store_id, &gen_sku, self_id).await?;
            let barcode_clash = want_barcode && barcode_taken(conn, &ctx.store_id, &gen_barcode, self_id).await?;
            if sku_clash || barcode_clash {
                continue;
            }
            if want_sku {
                sku = Some(gen_sku);
            }
            if want_barcode {
                barcode = Some(gen_barcode);
            }
            break;
        }
    }
    Ok((sku, barcode))
}

