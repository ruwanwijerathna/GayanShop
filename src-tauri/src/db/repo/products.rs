const PRODUCT_COLS: &str = "p.id, p.kind, p.name, p.name_si, p.sku, p.barcode, p.category_id, p.default_cost, p.price,
    p.min_price, p.track_stock, p.allow_negative_stock, p.attributes, p.is_active, p.barcode_conflict, p.created_at, p.updated_at,
    p.version, COALESCE(sl.on_hand, 0) AS on_hand";

/// `products p` plus its derived stock level (`PRODUCT_COLS` reads `sl.on_hand`).
const PRODUCT_FROM: &str = "products p LEFT JOIN stock_levels sl ON sl.product_id = p.id";

const SUMMARY_COLS: &str = "p.id, p.kind, p.name, p.name_si, p.sku, p.barcode, p.price, p.min_price, p.track_stock";

/// Hot read paths, public so `tests/perf_budgets.rs` can `EXPLAIN QUERY PLAN` the exact SQL (doc §13.4).
/// Scanner lookup by barcode: `idx_products_barcode` (partial index; several products may share a barcode).
pub static SQL_LOOKUP_BARCODE: LazyLock<String> = LazyLock::new(|| {
    format!(
        "SELECT {SUMMARY_COLS} FROM products p
         WHERE p.store_id = ?1 AND p.barcode = ?2 AND p.deleted_at IS NULL AND p.is_active = 1
         ORDER BY p.name COLLATE NOCASE, p.id"
    )
});
/// Scanner lookup by in-store SKU: `ux_products_sku`.
pub static SQL_LOOKUP_SKU: LazyLock<String> = LazyLock::new(|| {
    format!(
        "SELECT {SUMMARY_COLS} FROM products p
         WHERE p.store_id = ?1 AND p.sku = ?2 AND p.deleted_at IS NULL AND p.is_active = 1"
    )
});
/// English type-ahead: `products_fts` (unicode61, prefix indexes), then the products PK.
pub static SQL_SEARCH_LATIN: LazyLock<String> = LazyLock::new(|| {
    format!(
        "SELECT {SUMMARY_COLS} FROM products_fts f JOIN products p ON p.id = f.id
         WHERE products_fts MATCH ?1 AND p.store_id = ?2 AND p.deleted_at IS NULL AND p.is_active = 1
         ORDER BY f.rank LIMIT ?3"
    )
});
/// Sinhala substring search (3+ characters): `products_fts_si` (trigram), then the products PK.
pub static SQL_SEARCH_SINHALA: LazyLock<String> = LazyLock::new(|| {
    format!(
        "SELECT {SUMMARY_COLS} FROM products_fts_si f JOIN products p ON p.id = f.id
         WHERE products_fts_si MATCH ?1 AND p.store_id = ?2 AND p.deleted_at IS NULL AND p.is_active = 1
         ORDER BY f.rank LIMIT ?3"
    )
});

