/// Rs 100,000,000.00 — far above any shop price; catches a mistyped extra zero run.
const MONEY_MAX: i64 = 10_000_000_000;
pub const SEARCH_LIMIT_MAX: u32 = 50;

#[derive(Debug, Clone, Copy, Serialize, Deserialize, Type, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum ProductKind {
    Standard,
    /// "Plasticware – any item Rs 250": one product standing for many unlabelled items.
    Generic,
}

impl ProductKind {
    fn code(self) -> &'static str {
        match self {
            ProductKind::Standard => "standard",
            ProductKind::Generic => "generic",
        }
    }

    fn parse(s: &str) -> AppResult<Self> {
        match s {
            "standard" => Ok(ProductKind::Standard),
            "generic" => Ok(ProductKind::Generic),
            other => Err(AppError::internal(format!("unknown product kind {other}"))),
        }
    }
}

/// How a code field is set when saving: cleared, generated by this counter, or typed/scanned.
#[derive(Debug, Clone, Deserialize, Type, PartialEq, Eq)]
#[serde(tag = "mode", rename_all = "snake_case")]
pub enum CodeChoice {
    None,
    Generate,
    Manual { value: String },
}

/// The full product, for the back office. `default_cost` is `None` unless the viewer holds `VIEW_COST`.
