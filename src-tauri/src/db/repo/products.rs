/// Every live product (active and inactive), newest first. Bounded (≤ ~50k), so the back office loads
/// it once and filters client-side (doc §1.4).
pub async fn list(pool: &SqlitePool, store_id: &str, view_cost: bool) -> AppResult<Vec<Product>> {
    let rows: Vec<ProductRow> = sqlx::query_as(&format!(
        "SELECT {PRODUCT_COLS} FROM {PRODUCT_FROM} WHERE p.store_id = ?1 AND p.deleted_at IS NULL
         ORDER BY p.created_at DESC, p.id DESC"
    ))
    .bind(store_id)
    .fetch_all(pool)
    .await?;
    rows.into_iter().map(|r| r.into_product(view_cost)).collect()
}

async fn get_conn(conn: &mut SqliteConnection, store_id: &str, id: &str) -> AppResult<ProductRow> {
    sqlx::query_as(&format!(
        "SELECT {PRODUCT_COLS} FROM {PRODUCT_FROM} WHERE p.store_id = ?1 AND p.id = ?2 AND p.deleted_at IS NULL"
    ))
    .bind(store_id)
    .bind(id)
    .fetch_optional(&mut *conn)
    .await?
    .ok_or_else(|| AppError::not_found("product"))
}

pub async fn get(pool: &SqlitePool, store_id: &str, id: &str, view_cost: bool) -> AppResult<Product> {
    let mut conn = pool.acquire().await?;
    get_conn(&mut conn, store_id, id).await?.into_product(view_cost)
}

/// [`get`] on the caller's connection (inside a write transaction).
pub async fn get_on(conn: &mut SqliteConnection, store_id: &str, id: &str, view_cost: bool) -> AppResult<Product> {
    get_conn(conn, store_id, id).await?.into_product(view_cost)
}

/// The till's view of one active product, by id.
pub async fn summary(pool: &SqlitePool, store_id: &str, id: &str) -> AppResult<Option<ProductSummary>> {
    let p = match get(pool, store_id, id, false).await {
        Ok(p) => p,
        Err(AppError::NotFound { .. }) => return Ok(None),
        Err(e) => return Err(e),
    };
    if !p.is_active {
        return Ok(None);
    }
    Ok(Some(ProductSummary {
        id: p.id,
        kind: p.kind,
        name: p.name,
        name_si: p.name_si,
        sku: p.sku,
        barcode: p.barcode,
        price: p.price,
        min_price: p.min_price,
        track_stock: p.track_stock,
    }))
}

/// Scanner lookup (doc §7.4): every active product with this `barcode` (several variants can share one),
/// else the single product with this in-store `sku`. Empty = unknown code. Ordered by name.
pub async fn lookup_code_matches(pool: &SqlitePool, store_id: &str, code: &str) -> AppResult<Vec<ProductSummary>> {
    let code = code.trim();
    if code.is_empty() {
        return Ok(Vec::new());
    }
    let mut rows: Vec<SummaryRow> =
        sqlx::query_as(&SQL_LOOKUP_BARCODE).bind(store_id).bind(code).fetch_all(pool).await?;
    if rows.is_empty() {
        rows = sqlx::query_as(&SQL_LOOKUP_SKU).bind(store_id).bind(code).fetch_all(pool).await?;
    }
    rows.into_iter().map(SummaryRow::into_summary).collect()
}

fn is_sinhala(c: char) -> bool {
    ('\u{0D80}'..='\u{0DFF}').contains(&c)
}

/// `"blue buc"` → `"blue"* "buc"*` for the unicode61 table (every token is a prefix, all must match).
/// Only letters and digits survive, so user input can never inject FTS5 syntax.
pub fn latin_match_query(query: &str) -> Option<String> {
    let tokens: Vec<String> = query
        .split(|c: char| !c.is_alphanumeric())
        .filter(|t| !t.is_empty())
        .map(|t| format!("\"{}\"*", t.to_lowercase()))
        .collect();
    (!tokens.is_empty()).then(|| tokens.join(" "))
}

/// Type-ahead search over English names, SKUs and barcodes (unicode61 prefix index) or, when the query
/// contains Sinhala letters, over Sinhala names (trigram substring index). Active products only. An exact
/// barcode/SKU hit is listed first.
pub async fn search(pool: &SqlitePool, store_id: &str, query: &str, limit: u32) -> AppResult<Vec<ProductSummary>> {
    let query = query.trim();
    let limit = i64::from(limit.clamp(1, SEARCH_LIMIT_MAX));
    if query.is_empty() {
        return Ok(Vec::new());
    }
    let rows: Vec<SummaryRow> = if query.chars().any(is_sinhala) {
        if query.chars().count() >= 3 {
            // Trigram MATCH needs ≥ 3 characters; the phrase is matched as a substring.
            sqlx::query_as(&SQL_SEARCH_SINHALA)
                .bind(format!("\"{}\"", query.replace('"', "\"\"")))
                .bind(store_id)
                .bind(limit)
                .fetch_all(pool)
                .await?
        } else {
            sqlx::query_as(&format!(
                "SELECT {SUMMARY_COLS} FROM products_fts_si f JOIN products p ON p.id = f.id
                 WHERE f.name_si LIKE '%' || ?1 || '%' AND p.store_id = ?2 AND p.deleted_at IS NULL
                   AND p.is_active = 1
                 ORDER BY p.name_si LIMIT ?3"
            ))
            .bind(query.replace(['%', '_'], ""))
            .bind(store_id)
            .bind(limit)
            .fetch_all(pool)
            .await?
        }
    } else {
        let Some(fts) = latin_match_query(query) else {
            return Ok(Vec::new());
        };
        sqlx::query_as(&SQL_SEARCH_LATIN).bind(fts).bind(store_id).bind(limit).fetch_all(pool).await?
    };
    let mut hits: Vec<ProductSummary> = rows.into_iter().map(SummaryRow::into_summary).collect::<AppResult<_>>()?;
    let looks_like_code = query.len() >= 4 && query.chars().all(|c| c.is_ascii_alphanumeric() || c == '-');
    if looks_like_code {
        let exact = lookup_code_matches(pool, store_id, query).await?;
        if !exact.is_empty() {
            hits.retain(|h| !exact.iter().any(|e| e.id == h.id));
            hits.splice(0..0, exact);
            hits.truncate(usize::try_from(limit).unwrap_or(usize::MAX));
        }
    }
    Ok(hits)
}

